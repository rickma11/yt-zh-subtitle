#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""中文字幕本地化润色：把 Google 直译的生硬输出替换为 FC27/足球圈通行说法。

原则：
- 只做高置信度替换（术语词典 + 轻量口语化规则），不改写句子结构，避免引入事实错误
- 词典按长度降序应用，长词优先防误伤（如"技能移动"先于"技能"）
- 幂等：重复执行结果一致
"""

# 术语层：gtx 英译中生硬直译 -> 游戏圈通行说法
TERMS = [
    ("技能移动", "花式动作"),
    ("技能动作", "花式动作"),
    ("技能招式", "花式动作"),
    ("技巧动作", "花式动作"),
    ("技巧移动", "花式动作"),
    ("手动选择", "手动切换"),
    ("精细射门", "搓射"),
    ("力量射门", "爆射"),
    ("改变方向", "变向"),
    ("人工智能", "AI"),
    ("终极球队", "UT"),
    ("防守者", "防守球员"),
    ("守门员", "门将"),
    ("普通卡", "普卡"),
    ("特殊卡", "色卡"),
    ("非常重要", "特别关键"),
    ("极其有效", "特别有效"),
    ("我将向您展示", "给大家演示"),
    ("我将向大家展示", "给大家演示"),
    ("向大家展示", "给大家演示"),
    ("在本视频中", "这期视频"),
    ("最有效的", "最实用的"),
    ("伙计们", "兄弟们"),
    ("您", "你"),
    ("极其", "特别"),
    ("技能", "花式"),
    ("花式点", "技能点"),   # 还原"技能点"被误伤
    ("1v1", "1对1"),
    ("1V1", "1对1"),
]

import re  # noqa: E402

# 口语化/清理规则（正则）
RULES = [
    (re.compile(r"1对1s"), "1对1"),
    (re.compile(r"极其(困难|难)"), "特别难"),
    # gtx 偶发半角标点 -> 全角
    (re.compile(r","), "，"),
    (re.compile(r";"), "；"),
    (re.compile(r"(?<!\d):(?!\d)"), "："),
]


def polish(text):
    if not text:
        return text
    for src, dst in sorted(TERMS, key=lambda kv: -len(kv[0])):
        text = text.replace(src, dst)
    for pat, dst in RULES:
        text = pat.sub(dst, text)
    return text


if __name__ == "__main__":
    demo = [
        "他们的防守者，适当时机的技能移动可以使他们变得极其困难",
        "在本视频中，我将向您展示 FC 27 上 5 个最有效的 1v1 技能，如何",
        "你需要手动选择你的防守者来应对人工智能控制的进攻",
    ]
    for d in demo:
        print("原文:", d)
        print("润色:", polish(d))
        print()
